// Bundle local graphics into one portable HTML file without changing the source.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const input = path.join(root, '포털_인터랙션.html');
const output = path.join(root, '포털_인터랙션_단일파일.html');
const portableOutput = path.join(root, '멀티버스_포털_체험.html');
const comicOutput = path.join(root, '멀티버스_포털_코믹스.html');
const palmOutput = path.join(root, '멀티버스_포털_입장_손바닥.html');
const handMagicOutput = path.join(root, '멀티버스_포털_손바닥마법.html');
const fixedPersonOutput = path.join(root, '멀티버스_포털_손바닥마법_v2.html');
const assets = new Set();
const source = fs.readFileSync(input, 'utf8');
const html = source.replace(/(['"])(assets\/[^'"\r\n]+\.(?:png|jpe?g|webp))\1/g, (_, quote, relative) => {
  const asset = path.resolve(root, relative);
  assert.ok(asset.startsWith(path.join(root, 'assets') + path.sep));
  assets.add(relative);
  const extension = path.extname(asset).toLowerCase();
  const mime = extension === '.png' ? 'image/png' : extension === '.webp' ? 'image/webp' : 'image/jpeg';
  return quote + 'data:' + mime + ';base64,' + fs.readFileSync(asset).toString('base64') + quote;
});
assert.equal(assets.size, 15, 'All ten portal backgrounds, four Avengers, and the snowfield must be embedded');
assert.ok(!/(['"])assets\/[^'"]+\1/.test(html), 'No local image dependencies may remain');
for (const match of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)) new Function(match[1]);
fs.writeFileSync(output, html, 'utf8');
fs.writeFileSync(portableOutput, html, 'utf8');
fs.writeFileSync(comicOutput, html, 'utf8');
fs.writeFileSync(palmOutput, html, 'utf8');
fs.writeFileSync(handMagicOutput, html, 'utf8');
fs.writeFileSync(fixedPersonOutput, html, 'utf8');
console.log('Saved:', output);
console.log('Saved:', portableOutput);
console.log('Saved:', comicOutput);
console.log('Saved:', palmOutput);
console.log('Saved:', handMagicOutput);
console.log('Saved:', fixedPersonOutput);
console.log('Embedded images:', assets.size);
console.log('Size:', Math.round(Buffer.byteLength(html) / 1024 / 1024 * 10) / 10, 'MB');
